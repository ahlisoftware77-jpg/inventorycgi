const parsed2 = parsed1.replace(/^"|"$/g, '').trim();
console.log('After replacing \\n and quotes:');
console.log('Includes literal \\n:', parsed2.includes('\\n'));
console.log('Includes real newline:', parsed2.includes('\n'));
console.log('Starts with:', parsed2.substring(0, 30));
