require('dotenv').config();
const key = process.env.FIREBASE_PRIVATE_KEY || '';
console.log('Raw length:', key.length);
console.log('Includes literal \\n:', key.includes('\\n'));
console.log('Includes real newline:', key.includes('\n'));
